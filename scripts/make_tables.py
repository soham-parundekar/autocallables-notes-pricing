"""Generate the report's tables from the saved results.

The numbers in the report are produced here rather than typed, so a table
cannot drift from the run that produced it. `reports/tables.md` is regenerated
by `make report` and the report text cites it.
"""

from __future__ import annotations

import argparse
import json
import sys
from itertools import count
from pathlib import Path

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.analysis.results import ISSUER_SHORT, barrier_coverage, load_results

CALL_LABEL = {
    "issuer_discretionary": "issuer's option",
    "rational_exercise": "rational-exercise rule",
    "automatic": "automatic at 93.25%",
}


def basis_points(spread: dict | None) -> str:
    """The spread in basis points, or why there is no number to print.

    The unit belongs inside this function. Appending " bp" at the call site
    glued it onto the two sentinels as well, so a cell with no solved spread
    printed "no solution bp", which reads as a quantity.
    """
    if not spread:
        return "n/a"
    if not spread.get("bracketed"):
        return "no solution"
    return f"{spread['spread'] * 1e4:+,.0f} bp"


def main(root: Path) -> None:
    notes = {n["id"]: n for n in yaml.safe_load((root / "config/notes.yaml").read_text())["notes"]}
    results, meta = load_results(root)
    analysis = {"generated_for_snapshot": meta.get("snapshot"),
                "convergence": meta.get("convergence") or {}}
    lines: list[str] = []
    counter = count(1)

    def section(title: str) -> None:
        """Open a numbered section.

        The numbers come from the counter rather than the call site, because
        some sections only appear when the run that produced them exists. With
        the number written into the title, skipping the convergence study left
        a gap between Table 7 and Table 9 in the published file.
        """
        lines.extend(["", f"### Table {next(counter)}. {title}", ""])

    lines.append("<!-- Generated by scripts/make_tables.py. Do not edit by hand. -->")
    lines.append(f"<!-- Option snapshot: {analysis['generated_for_snapshot']} -->")

    # A note whose barrier falls outside quoted strikes on any leg is priced off
    # an extrapolation there and is held out of the report's ranges. Marking it
    # in the table keeps the number visible and its status with it.
    coverage = barrier_coverage(root)
    held_out = sorted(
        note_id for note_id in results
        if not coverage.get(note_id, {}).get("fully_covered", True)
    )

    section("Model value against the disclosed estimated value")
    lines.append("| Note | Issuer | Tenor | Coupon | Call | Model value | s.e. | Disclosed | Gap | Gap % |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for note_id, result in results.items():
        base, margin = result["base"], result["margin"]
        gap = base["value"] - margin["disclosed_estimated_value"]
        mark = " \\*" if note_id in held_out else ""
        lines.append(
            f"| {note_id}{mark} | {ISSUER_SHORT.get(base['issuer'], base['issuer'])} "
            f"| {base['tenor_years']:.2f}y | {base['coupon_rate'] * 100:.2f}% "
            f"| {CALL_LABEL.get(base['call_style'], base['call_style'])} "
            f"| {base['value']:,.2f} | {base['stderr']:.2f} "
            f"| {margin['disclosed_estimated_value']:,.2f} | {gap:+,.2f} "
            f"| {100 * gap / margin['disclosed_estimated_value']:+.2f}% |"
        )
    if held_out:
        legs = []
        for note_id in held_out:
            for ticker, leg in coverage[note_id]["legs"].items():
                if leg["covered"] == 0:
                    legs.append(f"{note_id}'s {ticker} leg ({leg['covered']}/{leg['slices']})")
        lines.append("")
        lines.append(
            f"\\* Held out of the ranges quoted in the report: "
            f"{', '.join(legs)} has no quoted strike at the note's barrier on any "
            f"fitted slice past one year, so its downside is extrapolated rather "
            f"than observed. The value is reported, not relied on."
        )

    section("What the issuer keeps, with no model involved")
    lines.append("This is the issuer's own arithmetic from the filing: issue price "
                 "less the disclosed estimated value less the commission.")
    lines.append("")
    lines.append("| Note | Issuer | Issue price | Disclosed value | Commission | "
                 "Value gap | Residual | Residual % |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for note_id, result in results.items():
        m = result["margin"]
        lines.append(
            f"| {note_id} | {ISSUER_SHORT.get(m['issuer'], m['issuer'])} "
            f"| {m['denomination']:,.0f} | {m['disclosed_estimated_value']:,.2f} "
            f"| {m['selling_commission']:,.2f} | {m['ev_gap']:,.2f} "
            f"| {m['residual_margin']:,.2f} | {m['residual_margin_pct']:+.2f}% |"
        )

    section("Implied funding spread, under two call assumptions")
    oas = next(iter(results.values()))["corporate_oas_benchmark"]
    lines.append(
        f"Benchmark: {oas['description']}, {oas['oas_bp']:.0f} bp on {oas['as_of']} "
        "(FRED series `BAMLC0A3CA`). A funding spread should be positive and wider "
        "than this, since a note's funding is dearer than the issuer's plain bonds."
    )
    lines.append("")
    lines.append("| Note | Disclosed | Model, optimal exercise | Implied spread | "
                 "Model, call ignored | Implied spread |")
    lines.append("|---|---|---|---|---|---|")
    for note_id, result in results.items():
        disclosed = result["margin"]["disclosed_estimated_value"]
        optimal = result["implied_spread_optimal_exercise"]
        no_call = result["implied_spread_no_early_call"]
        no_call_value = (
            f"{no_call['value_at_zero_spread']:,.2f}" if no_call else "not applicable"
        )
        lines.append(
            f"| {note_id} | {disclosed:,.2f} | {result['base']['value']:,.2f} "
            f"| {basis_points(optimal)} | {no_call_value} | {basis_points(no_call)} |"
        )
    lines.append("")
    lines.append("The auto-callable note has no no-call column: its redemption is "
                 "mechanical and contractual, so removing it describes a different "
                 "security rather than a different modelling assumption.")

    section("Risk, per $1,000 of principal")
    lines.append("| Note | Delta per 1% move (by underlying) | Total vega per vol pt | "
                 "Value per +0.05 correlation | Investor long correlation? |")
    lines.append("|---|---|---|---|---|")
    for note_id, result in results.items():
        deltas = ", ".join(
            f"{d['underlying']} {d['delta_per_1pct']:+.2f}" for d in result["deltas"]
        )
        vega = sum(v["vega_per_vol_point"] for v in result["bucketed_vega"])
        correlation = result["correlation"]
        lines.append(
            f"| {note_id} | {deltas} | {vega:+.2f} "
            f"| {correlation['d_value_per_0.05']:+.2f} "
            f"| {'yes' if correlation['investor_is_long_correlation'] else 'no'} |"
        )

    section("Economic decomposition")
    lines.append("| Note | Funding bond | Coupon strip | Worst-of put | Issuer's call | "
                 "Value without call | Value with call |")
    lines.append("|---|---|---|---|---|---|---|")
    for note_id, result in results.items():
        d = result["decomposition"]
        lines.append(
            f"| {note_id} | {d['funding_bond']:,.2f} | {d['coupon_strip']:,.2f} "
            f"| −{d['worst_of_put_cost']:,.2f} | −{d['issuer_call_cost']:,.2f} "
            f"| {d['value_without_call']:,.2f} | {d['value_with_call']:,.2f} |"
        )

    # Without this the last column sits a few points away from Table 1 with no
    # stated reason, which reads as a contradiction rather than a coarser
    # estimate of the same number.
    risk_paths = {r["risk_paths"] for r in results.values()}
    base_paths = {r["base"]["paths"] for r in results.values()}
    if len(risk_paths) == 1 and len(base_paths) == 1:
        lines.append(
            f"\nThe decomposition runs on the risk path set, {risk_paths.pop():,} paths "
            f"with no control variate, because every part has to be simulated under the "
            f"same draws for the parts to add up. Table 1 reports the headline estimator: "
            f"{base_paths.pop():,} paths with the European control variate. The last column "
            f"is therefore a coarser estimate of the Table 1 value, not a competing one, "
            f"and the two differ by sampling error. The residual column in the saved "
            f"results confirms the parts sum to the no-call value to within floating point."
        )

    section("Model risk")
    lines.append("| Note | Local vol | Flat vol | Smile effect | Extrapolation effect | "
                 "Timing effect | Years extrapolated (worst underlying) |")
    lines.append("|---|---|---|---|---|---|---|")
    for note_id, result in results.items():
        flat, extrapolation, timing = result["flat_vol"], result["extrapolation"], result["timing"]
        reliance = extrapolation["extrapolation_reliance"]
        worst = max(reliance.items(), key=lambda kv: kv[1]["extrapolated_years"])
        lines.append(
            f"| {note_id} | {flat['local_vol_value']:,.2f} | {flat['flat_vol_value']:,.2f} "
            f"| {flat['difference']:+,.2f} | {extrapolation['difference']:+,.2f} "
            f"| {timing['difference']:+,.2f} "
            f"| {worst[0]} {worst[1]['extrapolated_years']:.2f}y |"
        )

    section("Loss and redemption statistics")
    lines.append("| Note | P(redeemed early) | Expected life | P(principal loss) | "
                 "Expected loss given loss | P(knock-in touched) |")
    lines.append("|---|---|---|---|---|---|")
    for note_id, result in results.items():
        base = result["base"]
        knock_in = (
            f"{base['prob_knocked_in']:.3f}"
            if base["downside_observation"] == "american" else "n/a, European"
        )
        lines.append(
            f"| {note_id} | {base['prob_called']:.3f} | {base['expected_life_years']:.2f}y "
            f"| {base['prob_principal_loss']:.3f} "
            f"| {base['expected_loss_given_loss']:,.0f} | {knock_in} |"
        )

    if analysis.get("convergence"):
        section("Convergence")
        lines.append("| Note | Paths | Value | Standard error |")
        lines.append("|---|---|---|---|")
        for note_id, rows in sorted(analysis["convergence"].items()):
            for row in rows:
                lines.append(
                    f"| {note_id} | {row['paths']:,} | {row['value']:,.2f} | {row['stderr']:.3f} |"
                )

    section("Variance reduction from the control variates")
    lines.append("| Note | s.e. without controls | s.e. with controls | Variance reduction |")
    lines.append("|---|---|---|---|")
    for note_id, result in results.items():
        base = result["base"]
        lines.append(
            f"| {note_id} | {base['stderr_no_control_variate']:.3f} | {base['stderr']:.3f} "
            f"| {base['variance_reduction_factor']:.2f}x |"
        )

    section("Measured volatility move over the pricing-date gap")
    lines.append("| Note | Pricing date | Underlying | Index | 30-day vol at pricing | "
                 "At snapshot | Move |")
    lines.append("|---|---|---|---|---|---|---|")
    for note_id, result in results.items():
        pricing = result["base"]["pricing_date"]
        for move in result["timing"]["moves"]:
            if not np.isfinite(move.get("move_vol_points", float("nan"))):
                continue
            lines.append(
                f"| {note_id} | {pricing} | {move['ticker']} | {move['index']} "
                f"| {move['level_start']:.2f} | {move['level_end']:.2f} "
                f"| {move['move_vol_points'] * 100:+.2f} |"
            )

    attribution = root / "data/processed/call_attribution.json"
    if attribution.exists():
        payload = json.loads(attribution.read_text())
        used = sorted({float(r["funding_spread_bp"]) for r in payload["notes"]})
        at = (f"at {used[0]:.0f} bp" if len(used) == 1
              else "at each note's own pricing-date spread")
        section(
            f"How much of its own call does the disclosed value charge for? ({at})"
        )
        lines.append("| Note | Spread | No call | Optimal exercise | Call worth | "
                     "Disclosed | Disclosed less no-call | Fraction of call charged |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for row in payload["notes"]:
            if not row.get("applicable"):
                lines.append(
                    f"| {row['note_id']} | {row['funding_spread_bp']:.0f} bp "
                    f"| n/a | {row['value_optimal']:,.2f} | n/a "
                    f"| {row['disclosed_estimated_value']:,.2f} | n/a | "
                    f"not applicable: {row['reason']} |"
                )
                continue
            lines.append(
                f"| {row['note_id']} | {row['funding_spread_bp']:.0f} bp "
                f"| {row['value_no_call']:,.2f} "
                f"| {row['value_optimal']:,.2f} | {row['call_value']:,.2f} "
                f"| {row['disclosed_estimated_value']:,.2f} "
                f"| {row['residual_vs_no_call']:+,.2f} "
                f"| {row['implied_call_fraction']:+.2f} |"
            )

    proxy_summary = root / "data/processed/proxy_summary.csv"
    if proxy_summary.exists():
        import csv

        section("Cash index against its ETF proxy, at shared expiries")
        lines.append("| Index | ETF | Shared expiries | Longest shared | "
                     "Mean ETF less index | Worst |")
        lines.append("|---|---|---|---|---|---|")
        for row in csv.DictReader(proxy_summary.read_text().splitlines()):
            if not row.get("shared_expiries") or int(row["shared_expiries"]) == 0:
                continue
            lines.append(
                f"| {row['index']} | {row['etf']} | {row['shared_expiries']} "
                f"| {float(row['t_max_shared']):.2f}y "
                f"| {float(row['mean_difference_vol_pts']):+.3f} vol pts "
                f"| {float(row['max_abs_difference_vol_pts']):.3f} |"
            )
        risk = root / "data/processed/proxy_risk.json"
        if risk.exists():
            lines.append("")
            for row in json.loads(risk.read_text())["notes"]:
                shifts = ", ".join(f"{t} {v:+.3f} vol pts"
                                   for t, v in row["shift_vol_points"].items())
                lines.append(
                    f"Correcting {shifts} on {row['note_id']} moves it from "
                    f"{row['value_as_calibrated']:,.2f} to "
                    f"{row['value_proxy_corrected']:,.2f} "
                    f"({row['difference']:+.2f}, s.e. {row['stderr']:.2f}), "
                    f"narrowing its gap from {row['gap_as_calibrated']:,.2f} to "
                    f"{row['gap_proxy_corrected']:,.2f}."
                )

    target = root / "reports/tables.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n")
    print(f"wrote {target.relative_to(root)} ({len(results)} notes, {len(lines)} lines)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    main(parser.parse_args().root)
